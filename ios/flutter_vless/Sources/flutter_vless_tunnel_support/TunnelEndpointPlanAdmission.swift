import Foundation

/// One session may keep its committed worker while a newer endpoint plan is
/// prepared. Only the latest plan may begin a new native runtime attempt.
public final class TunnelEndpointPlanAdmission: @unchecked Sendable {
    public struct Token: Equatable, Sendable {
        public let epoch: TunnelSessionAdmission.Epoch
        public let generation: UInt64
        fileprivate init(epoch: TunnelSessionAdmission.Epoch, generation: UInt64) {
            self.epoch = epoch
            self.generation = generation
        }
    }

    public enum Failure: Error { case stale, exhausted }

    private let lock = NSLock()
    private var sequence: UInt64 = 0
    private var pending: Token?
    private var committed: Token?

    public init() {}

    /// Called for an explicit session start. The sequence never resets, so
    /// callbacks from an earlier session cannot acquire a replacement token.
    public func begin(_ epoch: TunnelSessionAdmission.Epoch) throws -> Token {
        lock.lock(); defer { lock.unlock() }
        guard sequence < UInt64.max else { throw Failure.exhausted }
        sequence += 1
        let token = Token(epoch: epoch, generation: sequence)
        pending = token
        committed = nil
        return token
    }

    /// Path, wake, TTL and failed-transport refreshes supersede older candidate
    /// work without revoking the still-running committed worker.
    public func refresh(_ epoch: TunnelSessionAdmission.Epoch) throws -> Token {
        lock.lock(); defer { lock.unlock() }
        guard pending?.epoch == epoch else { throw Failure.stale }
        guard sequence < UInt64.max else { throw Failure.exhausted }
        sequence += 1
        let token = Token(epoch: epoch, generation: sequence)
        pending = token
        return token
    }

    public func isCurrent(_ token: Token) -> Bool {
        lock.lock(); defer { lock.unlock() }
        return pending == token
    }

    /// Commit only after candidate validation, the exact old worker drain and
    /// the candidate's protected network-settings completion. Duplicate handoff
    /// cannot admit a second attempt.
    @discardableResult
    public func commit(_ token: Token) -> Bool {
        lock.lock(); defer { lock.unlock() }
        guard pending == token, committed != token else { return false }
        committed = token
        return true
    }

    /// Existing traffic may remain healthy during preparation of a newer plan.
    public func ownsRuntime(_ token: Token) -> Bool {
        lock.lock(); defer { lock.unlock() }
        return committed == token
    }

    /// Restarting from old generated bytes after a refresh is forbidden, even
    /// while the previous committed worker is still allowed to finish traffic.
    public func mayStart(_ token: Token) -> Bool {
        lock.lock(); defer { lock.unlock() }
        return pending == token && committed == token
    }

    public var currentToken: Token? {
        lock.lock(); defer { lock.unlock() }
        return pending
    }

    public var committedToken: Token? {
        lock.lock(); defer { lock.unlock() }
        return committed
    }

    /// Revoking an old session cannot revoke the next explicit session.
    public func revoke(_ epoch: TunnelSessionAdmission.Epoch?) {
        lock.lock(); defer { lock.unlock() }
        guard let epoch else { return }
        if pending?.epoch == epoch { pending = nil }
        if committed?.epoch == epoch { committed = nil }
    }
}

/// A settings write is asynchronous and cannot be cancelled once submitted to
/// NetworkExtension. Retain FIFO ownership through its callback; a new plan must
/// not overtake that write. Callers recheck plan/session ownership after waits.
public final class TunnelEndpointCommitQueue: @unchecked Sendable {
    private let lock = NSLock()
    private var tail: Task<Void, Never>?

    public init() {}

    public func submit<Value>(_ operation: @escaping () async throws -> Value) -> Task<Value, Error> {
        lock.lock(); defer { lock.unlock() }
        let previous = tail
        let task = Task {
            await previous?.value
            return try await operation()
        }
        tail = Task { _ = try? await task.value }
        return task
    }
}
