Future<Uint8List> _download(Uri url, int limit) async {
  const timeout = Duration(seconds: 45);
  final client = HttpClient()..connectionTimeout = timeout;
  try {
    return await _readDownload(client, url, limit).timeout(timeout);
  } on Exception catch (error) {
    if (error is SetupException) rethrow;
    throw SetupException(
      'Could not download ${url.pathSegments.last} (${error.runtimeType}).',
    );
  } finally {
    client.close(force: true);
  }
}

Future<Uint8List> _readDownload(HttpClient client, Uri url, int limit) async {
  var uri = url;
  for (var redirects = 0; redirects <= 5; redirects++) {
    final request = await client.getUrl(uri);
    request.followRedirects = false;
    final response = await request.close();
    final status = response.statusCode;
    if (status == 301 ||
        status == 302 ||
        status == 303 ||
        status == 307 ||
        status == 308) {
      final location = response.headers.value(HttpHeaders.locationHeader);
      if (location == null) break;
      uri = uri.resolve(location);
      if (uri.scheme != 'https' || uri.userInfo.isNotEmpty) break;
      await response.drain<void>();
      continue;
    }
    if (status != HttpStatus.ok || response.contentLength > limit) {
      throw SetupException(
        'Download of ${url.pathSegments.last} failed (HTTP $status or oversized response).',
      );
    }
    final bytes = BytesBuilder(copy: false);
    await for (final chunk in response) {
      if (bytes.length + chunk.length > limit) {
        throw SetupException(
            'Download of ${url.pathSegments.last} exceeds its size limit.');
      }
      bytes.add(chunk);
    }
    return bytes.takeBytes();
  }
  throw SetupException(
      'Invalid HTTPS redirect while downloading ${url.pathSegments.last}.');
}
