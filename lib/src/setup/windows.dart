const _cmakePath = 'windows/CMakeLists.txt';
const _fragmentPath = 'windows/flutter_vless_runtime.cmake';
const _managedInclude =
    r'include("${CMAKE_CURRENT_LIST_DIR}/flutter_vless_runtime.cmake")';
const _fragmentHeader = '# Generated by flutter_vless setup.';
const _managedDirectory = '.flutter_vless/runtime';
const _coreFiles = [
  'xray.exe',
  'geoip.dat',
  'geosite.dat',
  'LICENSE.xray-core'
];
const _tunnelFiles = [
  'tun2socks.exe',
  'wintun.dll',
  'LICENSE.tun2socks',
  'LICENSE.wintun',
];

typedef WindowsRuntimeDownload = Future<Uint8List> Function(Uri, int);

void planWindows(
  SetupRequest request,
  SetupPlan plan, {
  WindowsRuntimeDownload download = _download,
}) {
  final cmakeFile = File(request.resolve(_cmakePath));
  if (!_isRegularFile(cmakeFile)) {
    throw const SetupException(
      'Missing windows/CMakeLists.txt. Add the Windows platform to the Flutter project first.',
    );
  }
  final architecture = _architecture(request.architecture);
  final vpn = request.mode == SetupMode.vpn;
  final stage = 'windows/$_managedDirectory/$architecture';
  final marker = File(request.resolve('$stage/.custom-runtime'));
  final required = [
    'xray.exe',
    if (vpn) ...['tun2socks.exe', 'wintun.dll']
  ];
  final possible = [..._coreFiles, if (vpn) ..._tunnelFiles];
  final defaultSource = Directory(request.resolve('windows/xray'));
  final source = request.runtimeDirectory == null
      ? (_isRegularFile(File.fromUri(defaultSource.uri.resolve('xray.exe')))
          ? defaultSource
          : null)
      : Directory(request.resolve(request.runtimeDirectory!));

  final fragment = File(request.resolve(_fragmentPath));
  if (_isRegularFile(fragment) &&
      !fragment.readAsStringSync().startsWith('$_fragmentHeader\n')) {
    throw const SetupException(
      'windows/flutter_vless_runtime.cmake already exists and is not managed by flutter_vless.',
    );
  }

  final cmake = cmakeFile.readAsStringSync();
  final existingInclude =
      cmake.split('\n').where((line) => line.trim() == _managedInclude).length;
  if (existingInclude > 1 ||
      (existingInclude == 0 && cmake.contains('flutter_vless_runtime.cmake'))) {
    throw const SetupException(
      'windows/CMakeLists.txt has a conflicting flutter_vless_runtime.cmake include.',
    );
  }
  if (existingInclude == 0) {
    if (!RegExp(r'^\s*install\s*\(\s*TARGETS\b',
            multiLine: true, caseSensitive: false)
        .hasMatch(cmake)) {
      throw const SetupException(
        'The Windows project uses custom installation rules. Add the Flutter Runner install target before running setup.',
      );
    }
    if (_installsRuntime(cmake)) {
      throw const SetupException(
        'windows/CMakeLists.txt already installs an Xray runtime. Keep that install rule and manage its runtime files there.',
      );
    }
    final newline = cmake.contains('\r\n') ? '\r\n' : '\n';
    final separator = cmake.endsWith('\n') ? newline : '$newline$newline';
    plan.writeText(_cmakePath, '$cmake$separator$_managedInclude$newline');
  }
  _ignoreRuntime(request, plan);

  if (source != null || _isRegularFile(marker)) {
    _planCustomRuntime(
        request, plan, source, architecture, stage, required, possible);
    plan.notes.add('Windows uses the supplied $architecture runtime.');
  } else {
    if (architecture != 'x64') {
      throw const SetupException(
        'The pinned Windows runtime is available for x64. Supply a matching runtime with --runtime-dir, or prepare an x64 build on an x64 Windows host.',
      );
    }
    final sources = [
      _managedCore,
      if (vpn) ...[_tun2socks, _wintun, _tun2socksLicense],
    ];
    for (final pinned in sources) {
      final missing = <String>[];
      for (final member in pinned.members.values) {
        final file = File(request.resolve('$stage/${member.name}'));
        if (!_isRegularFile(file)) {
          missing.add(member.name);
          continue;
        }
        if (!_matchesDigest(file, member.sha256)) {
          throw SetupException(
            '${file.path} differs from the pinned runtime. Move it aside to reinstall or supply a custom runtime with --runtime-dir.',
          );
        }
      }
      if (missing.isEmpty) continue;
      plan.defer('Download and verify ${pinned.label}', () async {
        final archive = await download(Uri.parse(pinned.url), pinned.maxBytes);
        return _verifyRuntime(pinned, archive, missing, architecture);
      }, (files) {
        for (final entry in files.entries) {
          final destination = File(request.resolve('$stage/${entry.key}'));
          if (_isRegularFile(destination) &&
              !_matchesDigest(destination, _digest(entry.value))) {
            throw SetupException('${destination.path} changed during setup.');
          }
          plan.writeBytes('$stage/${entry.key}', entry.value);
        }
      });
    }
    plan.notes.add('Windows uses pinned x64 Xray 26.11.9-r1.');
  }

  plan.writeText(
      _fragmentPath, _cmakeFragment(architecture, required, possible));
  plan.notes.add(
    'Use flutter build windows on a Windows $architecture host with Visual Studio C++ tools.${vpn ? ' VPN mode requires an elevated app process.' : ''}',
  );
}

Future<Map<String, Uint8List>> _verifyRuntime(
  _RuntimeSource source,
  Uint8List archive,
  List<String> missing,
  String architecture,
) =>
    Isolate.run(() => source.verify(archive, missing, architecture));

/// Inspect Driver Store without editing the project or creating an adapter.
Future<WindowsWintunStaging> inspectWindowsWintun(
  SetupRequest request, {
  WindowsWintunCommand run = runWindowsWintunCommand,
}) async {
  const stage = 'windows/$_managedDirectory/x64';
  if (_architecture(request.architecture) != 'x64' ||
      _architecture(null) != 'x64' ||
      request.runtimeDirectory != null ||
      _isRegularFile(File(request.resolve('windows/xray/xray.exe'))) ||
      _isRegularFile(File(request.resolve('$stage/.custom-runtime')))) {
    throw const SetupException(
      '--stage-wintun requires native Windows x64 and the pinned VPN runtime.',
    );
  }
  final dll = File(request.resolve('$stage/wintun.dll'));
  final result = await run('inspect', dll);
  return WindowsWintunStaging(result == WindowsWintunResult.present, dll, run);
}

void _ignoreRuntime(SetupRequest request, SetupPlan plan) {
  const relative = 'windows/.gitignore';
  const rule = '/.flutter_vless/';
  final file = File(request.resolve(relative));
  final existing = _isRegularFile(file) ? file.readAsStringSync() : '';
  if (existing.split('\n').any((line) => line.trim() == rule)) return;
  final newline = existing.contains('\r\n') ? '\r\n' : '\n';
  final separator = existing.isEmpty || existing.endsWith('\n') ? '' : newline;
  plan.writeText(relative, '$existing$separator$rule$newline');
}

bool _installsRuntime(String cmake) {
  final statements = RegExp(
    r'^\s*install\s*\([\s\S]*?\)\s*$',
    caseSensitive: false,
    multiLine: true,
  );
  return statements.allMatches(cmake).any((entry) => RegExp(
        r'\bxray(?:\.exe|[/\\]|\b)|\btun2socks\.exe\b|\bwintun\.dll\b',
        caseSensitive: false,
      ).hasMatch(entry.group(0)!));
}

String _architecture(String? requested) {
  final windowsHost = Platform.environment['PROCESSOR_ARCHITEW6432'] ??
      Platform.environment['PROCESSOR_ARCHITECTURE'];
  final value = requested?.toLowerCase() ??
      (Platform.isWindows && windowsHost?.toLowerCase() == 'arm64'
          ? 'arm64'
          : 'x64');
  return switch (value) {
    'x64' || 'amd64' || 'x86_64' => 'x64',
    'arm64' || 'aarch64' => 'arm64',
    _ => throw SetupException('Unsupported Windows architecture: $value.'),
  };
}

void _planCustomRuntime(
  SetupRequest request,
  SetupPlan plan,
  Directory? source,
  String architecture,
  String stage,
  List<String> required,
  List<String> possible,
) {
  if (source != null &&
      FileSystemEntity.typeSync(source.path) !=
          FileSystemEntityType.directory) {
    throw SetupException(
        'Windows runtime directory not found: ${source.path}.');
  }

  for (final name in possible) {
    final staged = File(request.resolve('$stage/$name'));
    final provided =
        source == null ? null : File.fromUri(source.uri.resolve(name));
    final file = provided != null &&
            (required.contains(name) || _isRegularFile(provided))
        ? provided
        : staged;
    if (!_isRegularFile(file)) {
      if (required.contains(name)) {
        throw SetupException(
          'Windows ${request.mode.name} requires ${file.path}. Supply a complete runtime with --runtime-dir.',
        );
      }
      continue;
    }
    final maxBytes =
        name.startsWith('LICENSE') ? 1024 * 1024 : 128 * 1024 * 1024;
    if (file.lengthSync() > maxBytes || file.lengthSync() == 0) {
      throw SetupException('Invalid Windows runtime file size: ${file.path}.');
    }
    final bytes = file.readAsBytesSync();
    if (required.contains(name)) _checkPe(bytes, architecture, name);
    if (file.path == staged.path) continue;
    if (_isRegularFile(staged) && !_matchesDigest(staged, _digest(bytes))) {
      throw SetupException(
        '${staged.path} differs from the supplied runtime. Move it aside before switching runtimes.',
      );
    }
    plan.writeBytes('$stage/$name', bytes);
  }
  plan.writeText('$stage/.custom-runtime', 'flutter_vless custom runtime\n');
}

bool _isRegularFile(File file) {
  final type = FileSystemEntity.typeSync(file.path, followLinks: false);
  if (type == FileSystemEntityType.notFound) return false;
  if (type != FileSystemEntityType.file) {
    throw SetupException('Expected a regular file at ${file.path}.');
  }
  return true;
}

String _digest(List<int> bytes) => sha256.convert(bytes).toString();

bool _matchesDigest(File file, String expected) =>
    file.lengthSync() <= 128 * 1024 * 1024 &&
    _digest(file.readAsBytesSync()) == expected;

void _checkPe(Uint8List bytes, String architecture, String name) {
  if (bytes.length >= 64 && bytes[0] == 0x4d && bytes[1] == 0x5a) {
    final data = ByteData.sublistView(bytes);
    final offset = data.getUint32(0x3c, Endian.little);
    final machine = architecture == 'x64' ? 0x8664 : 0xaa64;
    if (offset >= 64 &&
        offset <= bytes.length - 24 &&
        data.getUint32(offset, Endian.little) == 0x4550 &&
        data.getUint16(offset + 4, Endian.little) == machine) {
      final isDll = data.getUint16(offset + 22, Endian.little) & 0x2000 != 0;
      if (isDll == name.endsWith('.dll')) return;
    }
  }
  throw SetupException(
      '$name is not a Windows $architecture PE image of the expected type.');
}

String _cmakeFragment(
  String architecture,
  List<String> required,
  List<String> possible,
) =>
    '''$_fragmentHeader
if(DEFINED FLUTTER_TARGET_PLATFORM AND NOT FLUTTER_TARGET_PLATFORM STREQUAL "windows-$architecture")
  message(FATAL_ERROR "flutter_vless runtime is configured for windows-$architecture. Rerun flutter_vless setup for the selected target.")
endif()
set(_flutter_vless_runtime "${r'${CMAKE_CURRENT_LIST_DIR}'}/$_managedDirectory/$architecture")
foreach(_flutter_vless_required IN ITEMS ${required.map((name) => '"$name"').join(' ')})
  if(NOT EXISTS "${r'${_flutter_vless_runtime}/${_flutter_vless_required}'}")
    message(FATAL_ERROR "Missing flutter_vless runtime file: ${r'${_flutter_vless_required}'}. Run flutter_vless setup.")
  endif()
endforeach()
foreach(_flutter_vless_file IN ITEMS ${possible.map((name) => '"$name"').join(' ')})
  if(EXISTS "${r'${_flutter_vless_runtime}/${_flutter_vless_file}'}")
    # Flutter's install prefix is a target directory generator expression.
    # Include it in the destination so CMake resolves it before installation.
    install(FILES "${r'${_flutter_vless_runtime}/${_flutter_vless_file}'}"
      DESTINATION "${r'${CMAKE_INSTALL_PREFIX}'}/xray" COMPONENT Runtime)
  endif()
endforeach()
unset(_flutter_vless_runtime)
unset(_flutter_vless_required)
unset(_flutter_vless_file)
''';

class _RuntimeFile {
  const _RuntimeFile(this.name, this.sha256);

  final String name;
  final String sha256;
}

class _RuntimeSource {
  const _RuntimeSource(
      this.label, this.url, this.sha256, this.maxBytes, this.members);

  final String label;
  final String url;
  final String sha256;
  final int maxBytes;
  final Map<String, _RuntimeFile> members;

  Map<String, Uint8List> verify(
    Uint8List bytes,
    List<String> missing,
    String architecture,
  ) {
    if (bytes.length > maxBytes || _digest(bytes) != sha256) {
      throw SetupException('$label SHA-256 does not match the pinned runtime.');
    }
    final archive = members.containsKey('')
        ? null
        : ZipDecoder().decodeBytes(bytes, verify: true);
    final extracted = <String, Uint8List>{};
    for (final entry in members.entries) {
      final member = entry.value;
      if (!missing.contains(member.name)) continue;
      final packed = archive?.findFile(entry.key);
      if (archive != null &&
          (packed == null ||
              !packed.isFile ||
              packed.isSymbolicLink ||
              packed.size > 128 * 1024 * 1024)) {
        throw SetupException('$label is missing the expected ${entry.key}.');
      }
      final content = packed?.content ?? bytes;
      if (_digest(content) != member.sha256) {
        throw SetupException('$label contains an invalid ${member.name}.');
      }
      if (member.name.endsWith('.exe') || member.name.endsWith('.dll')) {
        _checkPe(content, architecture, member.name);
      }
      extracted[member.name] = content;
    }
    return extracted;
  }
}

