    private fun coreEnvironmentUppercase(scalar: Int): Int {
        var low = 0
        var high = coreEnvironmentCase.size / 4
        while (low < high) {
            val middle = low + (high - low) / 2
            if (coreEnvironmentCase[middle * 4 + 1] < scalar) low = middle + 1 else high = middle
        }
        if (low == coreEnvironmentCase.size / 4) return scalar
        val offset = low * 4
        val first = coreEnvironmentCase[offset]
        return if (scalar >= first && (scalar - first) % coreEnvironmentCase[offset + 2] == 0)
            scalar + coreEnvironmentCase[offset + 3] else scalar
    }
