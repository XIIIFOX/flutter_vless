    // Go's Unicode White_Space set, shared by PortList and Address parsing.
    private static let goWhitespace = CharacterSet(charactersIn:
        "\u{0009}\u{000a}\u{000b}\u{000c}\u{000d} \u{0085}\u{00a0}\u{1680}\u{2000}\u{2001}\u{2002}\u{2003}\u{2004}\u{2005}\u{2006}\u{2007}\u{2008}\u{2009}\u{200a}\u{2028}\u{2029}\u{202f}\u{205f}\u{3000}")

    fileprivate static func trimCoreWhitespace(_ value: String) -> String {
        value.trimmingCharacters(in: goWhitespace)
    }

    fileprivate static func normalizedEnvironmentName(_ name: String) -> String {
        var scalars = String.UnicodeScalarView()
        for scalar in trimCoreWhitespace(name).unicodeScalars {
            let upper = coreEnvironmentUppercase(scalar.value)
            scalars.append(UnicodeScalar(upper == 0x2e ? 0x5f : upper)!)
        }
        return String(scalars)
    }

    fileprivate static func environmentValue(_ name: String, environment: (String) -> String?) -> String? {
        if let exact = environment(name) { return exact } // A present empty value wins.
        let alternate = normalizedEnvironmentName(name)
        return alternate.isEmpty ? nil : environment(alternate)
    }

