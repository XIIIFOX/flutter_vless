    private static func coreEnvironmentUppercase(_ scalar: UInt32) -> UInt32 {
        let value = Int32(scalar)
        var low = 0
        var high = coreEnvironmentCase.count / 4
        while low < high {
            let middle = low + (high - low) / 2
            if coreEnvironmentCase[middle * 4 + 1] < value { low = middle + 1 } else { high = middle }
        }
        guard low < coreEnvironmentCase.count / 4 else { return scalar }
        let offset = low * 4
        let first = coreEnvironmentCase[offset]
        return value >= first && (value - first) % coreEnvironmentCase[offset + 2] == 0
            ? UInt32(value + coreEnvironmentCase[offset + 3]) : scalar
    }
