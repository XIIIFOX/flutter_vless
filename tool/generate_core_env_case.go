// Generate the simple Unicode uppercase mapping used by Core's env aliases.
// This program imports only the standard library and never starts Xray.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"unicode"
)

const begin = "// BEGIN GENERATED CORE ENVIRONMENT CASE"
const end = "// END GENERATED CORE ENVIRONMENT CASE"

type caseRange struct{ first, last, step, delta int }

func ranges() ([]caseRange, int) {
	var points []caseRange
	for scalar := rune(0); scalar <= unicode.MaxRune; scalar++ {
		if upper := unicode.ToUpper(scalar); upper != scalar {
			points = append(points, caseRange{int(scalar), int(scalar), 1, int(upper - scalar)})
		}
	}
	var result []caseRange
	for i := 0; i < len(points); {
		current := points[i]
		next := i + 1
		if next < len(points) && points[next].delta == current.delta {
			step := points[next].first - current.first
			if step == 1 || step == 2 {
				current.step = step
				for next < len(points) && points[next].delta == current.delta &&
					points[next].first == current.last+step {
					current.last = points[next].first
					next++
				}
			}
		}
		result = append(result, current)
		i = next
	}
	// Check compression against the actual Go Unicode oracle, including every
	// identity scalar and every gap in a stride-two range.
	for scalar := 0; scalar <= unicode.MaxRune; scalar++ {
		index := sort.Search(len(result), func(i int) bool { return result[i].last >= scalar })
		upper := scalar
		if index < len(result) {
			entry := result[index]
			if scalar >= entry.first && (scalar-entry.first)%entry.step == 0 {
				upper += entry.delta
			}
		}
		if upper != int(unicode.ToUpper(rune(scalar))) {
			panic(fmt.Sprintf("uppercase compression mismatch U+%04X", scalar))
		}
	}
	return result, len(points)
}

func generated(language string, table []caseRange) string {
	var out strings.Builder
	out.WriteString(begin + "\n// Generated by tool/generate_core_env_case.go; Go Unicode " + unicode.Version + ".\n")
	switch language {
	case "cpp":
		out.WriteString("inline uint32_t GoEnvironmentUpper(uint32_t scalar) {\n  struct Range { uint32_t first, last, step; int32_t delta; };\n  static constexpr Range ranges[] = {\n")
		for _, entry := range table {
			fmt.Fprintf(&out, "    {%d, %d, %d, %d},\n", entry.first, entry.last, entry.step, entry.delta)
		}
		out.WriteString("  };\n  size_t low = 0, high = sizeof(ranges) / sizeof(ranges[0]);\n  while (low < high) {\n    const auto middle = low + (high - low) / 2;\n    if (ranges[middle].last < scalar) low = middle + 1; else high = middle;\n  }\n  if (low == sizeof(ranges) / sizeof(ranges[0])) return scalar;\n  const auto& range = ranges[low];\n  return scalar >= range.first && (scalar - range.first) % range.step == 0\n      ? static_cast<uint32_t>(static_cast<int64_t>(scalar) + range.delta) : scalar;\n}\n")
	case "kotlin":
		out.WriteString("    private val coreEnvironmentCase = intArrayOf(\n")
		for _, entry := range table {
			fmt.Fprintf(&out, "        %d, %d, %d, %d,\n", entry.first, entry.last, entry.step, entry.delta)
		}
		out.WriteString("    )\n    private fun coreEnvironmentUppercase(scalar: Int): Int {\n        var low = 0\n        var high = coreEnvironmentCase.size / 4\n        while (low < high) {\n            val middle = low + (high - low) / 2\n            if (coreEnvironmentCase[middle * 4 + 1] < scalar) low = middle + 1 else high = middle\n        }\n        if (low == coreEnvironmentCase.size / 4) return scalar\n        val offset = low * 4\n        val first = coreEnvironmentCase[offset]\n        return if (scalar >= first && (scalar - first) % coreEnvironmentCase[offset + 2] == 0)\n            scalar + coreEnvironmentCase[offset + 3] else scalar\n    }\n")
	case "swift":
		out.WriteString("    private static let coreEnvironmentCase: [Int32] = [\n")
		for _, entry := range table {
			fmt.Fprintf(&out, "        %d, %d, %d, %d,\n", entry.first, entry.last, entry.step, entry.delta)
		}
		out.WriteString("    ]\n    private static func coreEnvironmentUppercase(_ scalar: UInt32) -> UInt32 {\n        let value = Int32(scalar)\n        var low = 0\n        var high = coreEnvironmentCase.count / 4\n        while low < high {\n            let middle = low + (high - low) / 2\n            if coreEnvironmentCase[middle * 4 + 1] < value { low = middle + 1 } else { high = middle }\n        }\n        guard low < coreEnvironmentCase.count / 4 else { return scalar }\n        let offset = low * 4\n        let first = coreEnvironmentCase[offset]\n        return value >= first && (value - first) % coreEnvironmentCase[offset + 2] == 0\n            ? UInt32(value + coreEnvironmentCase[offset + 3]) : scalar\n    }\n")
	default:
		panic("unknown output language")
	}
	out.WriteString(end)
	return out.String()
}

func updateRegion(source []byte, replacement string) ([]byte, bool, error) {
	first, last := bytes.Index(source, []byte(begin)), bytes.Index(source, []byte(end))
	if first < 0 || last < first || bytes.Count(source, []byte(begin)) != 1 || bytes.Count(source, []byte(end)) != 1 {
		return nil, false, fmt.Errorf("exact generated region required")
	}
	previous := source[first : last+len(end)]
	if bytes.Equal(bytes.ReplaceAll(previous, []byte("\r\n"), []byte("\n")), []byte(replacement)) {
		return source, false, nil
	}
	// A Windows checkout can use CRLF. Check its content without rewriting it,
	// and retain that region's original newline style during regeneration.
	if bytes.Contains(previous, []byte("\r\n")) {
		replacement = strings.ReplaceAll(replacement, "\n", "\r\n")
	}
	result := append([]byte{}, source[:first]...)
	result = append(result, replacement...)
	result = append(result, source[last+len(end):]...)
	return result, true, nil
}

func main() {
	check := flag.Bool("check", false, "check generated regions without writing")
	summary := flag.Bool("summary", false, "verify Unicode compression and print counts only")
	root := flag.String("root", ".", "repository root")
	flag.Parse()
	if unicode.Version != "17.0.0" {
		fmt.Fprintln(os.Stderr, "Core env generation requires the pinned Go Unicode 17.0.0 tables")
		os.Exit(1)
	}
	table, count := ranges()
	if *summary {
		fmt.Printf("Unicode %s: %d changed scalars, %d ranges; all %d code points verified\n", unicode.Version, count, len(table), unicode.MaxRune+1)
		return
	}
	targets := []struct{ path, language string }{
		{"packages/flutter_vless_windows/windows/xray_config.h", "cpp"},
		{"packages/flutter_vless_android/android/src/main/kotlin/com/github/tfox/flutter_vless/xray/core/XrayPortSpec.kt", "kotlin"},
		{"ios/flutter_vless/Sources/flutter_vless_privacy/LocalProxyAccessPolicy.swift", "swift"},
		{"packages/flutter_vless_macos/macos/flutter_vless_macos/Sources/flutter_vless_macos_privacy/LocalProxyAccessPolicy.swift", "swift"},
	}
	// Read and validate all regions before writing any file.
	updated := make(map[string][]byte)
	for _, target := range targets {
		name := filepath.Join(*root, filepath.FromSlash(target.path))
		source, err := os.ReadFile(name)
		if err != nil {
			panic(err)
		}
		replacement := generated(target.language, table)
		result, stale, err := updateRegion(source, replacement)
		if err != nil {
			panic(err.Error() + ": " + target.path)
		}
		if stale {
			if *check {
				fmt.Fprintln(os.Stderr, "stale Core env uppercase mapping:", target.path)
				os.Exit(1)
			}
			updated[name] = result
		}
	}
	for name, data := range updated {
		if err := os.WriteFile(name, data, 0644); err != nil {
			panic(err)
		}
	}
	fmt.Printf("Core env Unicode %s: %d ranges; %d generated regions verified\n", unicode.Version, len(table), len(targets))
}
